#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int	cont;
	int	sign;
	int	i;

	cont = 0;
	sign = 1;
	i = 0;
	while (nptr[i] == ' ' || (nptr[i] >= '\t' && nptr[i] <= '\r'))
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			sign = -1;
		i++;
	}
	while (ft_isdigit(nptr[i]))
	{
		cont = (cont * 10) + (nptr[i] - '0');
		i++;
	}
	return (sign * cont);
}
