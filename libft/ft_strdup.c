#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*pt;
	int		i;

	pt = malloc(ft_strlen(s) + 1);
	if (pt)
	{
		i = 0;
		while (s[i] != '\0')
		{
			pt[i] = s[i];
			i++;
		}
		pt[i] = '\0';
	}
	return (pt);
}
